"""Files that collect follow up work for developers.

All files are written next to the log file. The conflict and protected branch lists are appended
to and skip entries that are already present, so repeated runs do not create duplicates.
"""

from __future__ import annotations

import shlex
from collections.abc import Iterable
from datetime import datetime
from pathlib import Path
from urllib.parse import quote

from gitlab_sync.config import Config
from gitlab_sync.results import BranchConflict, ProtectedPush, RollbackInstruction
from gitlab_sync.urls import UrlError, project_path

PROTECTED_HEADER = [
    "# Repos with a protected branch on the new instance",
    "",
    'The push was rejected with "You are not allowed to push code to protected branches".',
    "Open the link, allow the Maintainer role to push and merge on the branch, then run the sync",
    "again. Remove lines once they are done.",
    "",
]


def write_branch_conflicts(cfg: Config, conflicts: list[BranchConflict]) -> Path | None:
    """Append one line per branch that could not be merged."""
    path = cfg.output_path(cfg.conflicts_file)
    if not conflicts or path is None:
        return None
    stamp = f"{datetime.now():%Y-%m-%d %H:%M:%S}"
    known = {line.partition(" | ")[2] for line in _read_lines(path)}
    lines = []
    for item in conflicts:
        entry = (
            f"{cfg.relative_repo(item.repo)} | {item.branch} | "
            f"{cfg.old_remote}={item.old_sha[:10]} | {cfg.new_remote}={item.new_sha[:10]} | "
            f"{item.commits} commits"
        )
        if item.jenkins_rollback:
            entry += " | Jenkins rollback instructions"
        if entry not in known:
            known.add(entry)
            lines.append(f"{stamp} | {entry}")
    _append(path, lines)
    return path


def protected_branches_url(cfg: Config, new_url: str) -> str:
    """Link to the protected branches settings of the project on the new instance."""
    return f"{cfg.api_precheck.scheme}://{cfg.new_host}/{project_path(new_url)}{cfg.protected_branches_page}"


def write_protected_branches(cfg: Config, pushes: list[ProtectedPush]) -> Path | None:
    """Append one Markdown link per repo and branch whose push was rejected as protected."""
    path = cfg.output_path(cfg.protected_branches_file)
    if not pushes or path is None:
        return None
    existing = _read_lines(path)
    known = set(existing)
    lines = [] if existing else list(PROTECTED_HEADER)
    for push in pushes:
        try:
            link = protected_branches_url(cfg, push.new_url)
        except UrlError:
            link = push.new_url
        line = f"* [{cfg.relative_repo(push.repo)}]({link}) branch {push.branch}"
        if line not in known:
            known.add(line)
            lines.append(line)
    _append(path, lines)
    return path


def write_rollback_instructions(cfg: Config, items: list[RollbackInstruction]) -> Path | None:
    """Write the Jenkins rollback instructions. The file is replaced on every run that has any."""
    path = cfg.output_path(cfg.jenkins_rollback.instructions_file)
    if not items or path is None:
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_rollback_instructions(cfg, items), encoding="utf-8")
    return path


def render_rollback_instructions(cfg: Config, items: list[RollbackInstruction]) -> str:
    token = cfg.api_precheck.new_token_env
    dry_run_note = " in dry run mode, nothing was changed" if cfg.dry_run else ""
    lines = [
        "# Jenkins rollback: manual steps",
        "",
        f"Generated by gitlab_sync on {datetime.now():%Y-%m-%d %H:%M:%S}{dry_run_note}.",
        "",
        f"In these repos the merge from {cfg.old_host} fails because of Jenkins commits on the new",
        "instance. For each repo copy blocks A, B and C in that order into a terminal.",
        "",
        "Before you start:",
        "",
        f"* `{token}` must hold a token for the new instance with scope `api` and at least the",
        f"  Maintainer role, for example `export {token}=...`.",
        "* The SHAs reflect the state at generation time. If someone pushed to the branch since then,",
        "  `--force-with-lease` rejects the push. Run the sync again in that case.",
        "* Block B resets the branch and removes the Jenkins commits on the new instance. Jenkins",
        "  builds again after the push. Tags on the removed commits are kept.",
        "* `PATCH` on protected branches requires GitLab 15.6 or newer. On older versions remove the",
        "  protection with `DELETE` and create it again with",
        "  `POST ...?name=<branch>&allow_force_push=true`; note the access levels with `GET` first.",
        "  A `404` in block A or C means the branch is not protected, skip that block then.",
        "",
    ]
    for item in items:
        lines += _instruction_section(cfg, item, token)
    return "\n".join(lines)


def _instruction_section(cfg: Config, item: RollbackInstruction, token: str) -> list[str]:
    q = shlex.quote
    url = f"{_protected_branches_api(cfg, item.new_url)}/{quote(item.branch, safe='')}"
    lease = f"refs/heads/{item.branch}:{item.new_sha}"
    lines = [
        f"## {cfg.relative_repo(item.repo)}, branch `{item.branch}`",
        "",
        f"Jenkins commits on {cfg.new_remote}/{item.branch}, newest first:",
        "",
    ]
    lines += [f"* `{c.sha[:10]}` {c.subject} ({c.committer})" for c in item.commits]
    if item.tags:
        lines += ["", "Tags on these commits, they are kept: " + ", ".join(f"`{tag}`" for tag in item.tags)]
    lines += [
        "",
        "**A) Allow force push on the branch (API)**",
        "",
        "```bash",
        f': "${{{token}:?set {token} first}}"',
        f'curl -sS -H "PRIVATE-TOKEN: ${token}" {q(url)}   # show the current protection',
        f'curl -sS -w "\\nHTTP %{{http_code}}\\n" -X PATCH -H "PRIVATE-TOKEN: ${token}" '
        f"{q(url + '?allow_force_push=true')}",
        "```",
        "",
        "**B) Roll back, merge and force push (git)**",
        "",
        "```bash",
        f"cd {q(str(item.repo))} \\",
        f"  && git fetch {q(cfg.new_remote)} \\",
        f"  && git fetch {q(cfg.old_remote)} \\",
        f"  && git checkout -f -B {q(item.branch)} {q(cfg.new_remote + '/' + item.branch)} \\",
        f"  && git reset --hard {item.target_sha} \\",
        f"  && git merge --no-edit {q(cfg.old_remote + '/' + item.branch)} \\",
        f"  && git push --force-with-lease={q(lease)} {q(cfg.new_remote)} {q(item.branch)}",
        "```",
        "",
        "**C) Disallow force push again (API)**",
        "",
        "```bash",
        f'curl -sS -w "\\nHTTP %{{http_code}}\\n" -X PATCH -H "PRIVATE-TOKEN: ${token}" '
        f"{q(url + '?allow_force_push=false')}",
        "```",
        "",
    ]
    return lines


def _protected_branches_api(cfg: Config, new_url: str) -> str:
    try:
        project = quote(project_path(new_url), safe="")
    except UrlError:
        project = "GROUP%2FPROJECT"
    return f"{cfg.api_precheck.scheme}://{cfg.new_host}/api/v4/projects/{project}/protected_branches"


def _read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines() if path.exists() else []


def _append(path: Path, lines: Iterable[str]) -> None:
    lines = list(lines)
    if not lines:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
